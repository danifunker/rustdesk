#!/usr/bin/env python3
"""Assemble the tree the NT machine compiles: build/stage.

Visual C++ 4 (the compiler there is from 1996) knows C89 and Microsoft's own
extensions, and nothing of C99. The shared core is C89 apart from a few
things compat.h covers (inline, __attribute__, snprintf); what a header
cannot cover is rewritten here, mechanically, on the way:

    unsigned long long / long long   ->  unsigned __int64 / __int64
    123ULL / 123LL                   ->  123ui64 / 123i64
    __declspec(noinline)             ->  (nothing; Visual C++ 7 brought it)

    #define F(a, ...) / F(...)        ->  F(a) / F(x), every call cut to match

The last is for zstd, whose variadic macros only carry log text. Nothing
else is changed. Files are copied only when their staged content
differs, so a sync (scripts/ntx.py sync) sends only what changed.

Layout of build/stage:
    core/   crustdesk-macos-classic/src/core
    nacl/   third_party/libsodium-min
    bssl/   third_party/bearssl (inc/, src/)
    zstd/   third_party/zstd-decoder
    nt/     this port's src/, plus shim/stdint.h
    makefile  for nmake, written here

    stage.py [OUT]
"""
import os, re, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAC = os.path.join(HERE, "..", "crustdesk-macos-classic")
TP = os.path.join(MAC, "third_party")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "build", "stage")

CORE = ["vp8enc", "pb", "sha256", "session", "rng", "rdv", "unzstd", "files", "macbin",
        "console", "https", "anchors", "macroman", "png"]

R_ULL = re.compile(r"\b(0[xX][0-9a-fA-F]+|[0-9]+)[uU][lL][lL]\b")
R_LL = re.compile(r"\b(0[xX][0-9a-fA-F]+|[0-9]+)[lL][lL]\b")


def c89(text):
    text = re.sub(r"\bunsigned\s+long\s+long\b", "unsigned __int64", text)
    text = re.sub(r"\blong\s+long\b", "__int64", text)
    text = R_ULL.sub(r"\1ui64", text)
    text = R_LL.sub(r"\1i64", text)
    text = text.replace("__declspec(noinline)", "")
    return text


R_ANCHOR = re.compile(r"\{ \.(rsa|ec) = \{ ([^}]*) \} \}")


def anchors(text):
    """anchors.c (generated by tools/gen-anchors.py) names the member of
    br_x509_pkey's union it initialises, which C89 cannot: only the first,
    the RSA key, can be. An EC key is written through it instead. On NT, on
    every processor, int, size_t and pointers are all 32 bits, so
        rsa { unsigned char *n; size_t nlen; unsigned char *e; size_t elen; }
        ec  { int curve;        unsigned char *q; size_t qlen; }
    put curve where n is, q where nlen is, qlen where e is."""
    def one(m):
        if m.group(1) == "rsa":
            return "{ { %s } }" % m.group(2)
        curve, q, qlen = [a.strip() for a in m.group(2).split(",")]
        return "{ { (unsigned char *)%s, (size_t)%s, (unsigned char *)%s, 0 } }" % (
            curve, q.replace("(unsigned char *)", ""), qlen)
    return R_ANCHOR.sub(one, text)


R_VDEF = re.compile(r"^(\s*#\s*define\s+)(\w+)\(([^)]*)\.\.\.\)", re.M)


def call_args(text, i):
    """The arguments of a call whose '(' is at text[i]: [(start, end)], and
    the index of the closing ')'."""
    depth, args, start, j, q = 0, [], i + 1, i, None
    while j < len(text):
        c = text[j]
        if q:
            if c == "\\":
                j += 1
            elif c == q:
                q = None
        elif c in "\"'":
            q = c
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                args.append((start, j))
                return args, j
        elif c == "," and depth == 1:
            args.append((start, j))
            start = j + 1
        j += 1
    raise ValueError("unbalanced call")


def devariadic(text):
    """C99 variadic macros, for a compiler without them: each keeps its fixed
    parameters (one, if it had none), and every call drops the rest."""
    fixed = {}
    for m in R_VDEF.finditer(text):
        params = [p.strip() for p in m.group(3).split(",") if p.strip()]
        fixed[m.group(2)] = len(params)
    if not fixed:
        return text
    # the calls, first: a definition's own parameter list is not one
    for name, k in fixed.items():
        keep = max(k, 1)
        out, pos = [], 0
        for m in re.finditer(r"\b%s\s*\(" % re.escape(name), text):
            if m.start() < pos:
                continue
            line_start = text.rfind("\n", 0, m.start()) + 1
            if re.match(r"\s*#\s*define\s+%s\b" % re.escape(name), text[line_start:m.end()]):
                continue
            args, close = call_args(text, m.end() - 1)
            if len(args) <= keep:
                continue
            out.append(text[pos:args[keep - 1][1]])
            out.append(")")
            pos = close + 1
        out.append(text[pos:])
        text = "".join(out)
    # then the definitions, body and all (to the first line without a
    # trailing backslash): what stood for the dropped arguments becomes the
    # one argument of a macro that had no fixed ones, or nothing at all
    out, pos = [], 0
    for m in R_VDEF.finditer(text):
        if m.start() < pos:
            continue
        params = [p.strip() for p in m.group(3).split(",") if p.strip()]
        end = m.end()
        while True:
            nl = text.find("\n", end)
            if nl < 0:
                nl = len(text)
                break
            if not text[end:nl].rstrip().endswith("\\"):
                break
            end = nl + 1
        body = re.sub(r"\b__VA_ARGS__\b", "cdv_va" if not params else '""', text[m.end():nl])
        out.append(text[pos:m.start()])
        out.append("%s%s(%s)%s" % (m.group(1), m.group(2), ", ".join(params or ["cdv_va"]), body))
        pos = nl
    out.append(text[pos:])
    return "".join(out)


written = []


def put(src, rel):
    dst = os.path.join(OUT, rel)
    data = open(src, "rb").read()
    if src.endswith((".c", ".h")):
        text = c89(data.decode("latin-1"))
        if "__VA_ARGS__" in text:
            text = devariadic(text)
        if os.path.basename(src) == "anchors.c":
            text = anchors(text)
        data = text.encode("latin-1")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    try:
        if open(dst, "rb").read() == data:
            return
    except OSError:
        pass
    open(dst, "wb").write(data)
    written.append(rel)


def tree(src_dir, rel_dir, exts=(".c", ".h")):
    files = []
    for root, dirs, names in os.walk(src_dir):
        dirs.sort()
        for n in sorted(names):
            if n.endswith(exts):
                p = os.path.join(root, n)
                rel = os.path.join(rel_dir, os.path.relpath(p, src_dir))
                put(p, rel)
                files.append(rel)
    return files


def win(p):
    return p.replace("/", "\\")


def main():
    core_dir = os.path.join(MAC, "src", "core")
    for n in os.listdir(core_dir):
        if n.endswith(".h"):
            put(os.path.join(core_dir, n), "core/" + n)
    for n in CORE:
        put(os.path.join(core_dir, n + ".c"), "core/%s.c" % n)
    nacl = [f for f in tree(os.path.join(TP, "libsodium-min"), "nacl") if f.endswith(".c")]
    tree(os.path.join(TP, "bearssl", "inc"), "bssl/inc")
    bssl = [f for f in tree(os.path.join(TP, "bearssl", "src"), "bssl/src") if f.endswith(".c")]
    tree(os.path.join(TP, "zstd-decoder"), "zstd")
    nt = []
    for n in sorted(os.listdir(os.path.join(HERE, "src"))):
        p = os.path.join(HERE, "src", n)
        if os.path.isfile(p):
            put(p, "nt/" + n)
            if n.endswith(".c"):
                nt.append(n[:-2])
    put(os.path.join(HERE, "shim", "stdint.h"), "nt/stdint.h")
    res = os.path.join(HERE, "res")
    if os.path.isdir(res):
        for n in sorted(os.listdir(res)):
            put(os.path.join(res, n), "nt/" + n)

    build_id = os.environ.get("BUILD_ID", "dev")
    extra = os.environ.get("EXTRA_CFLAGS", "")
    m = []
    m.append("# Written by scripts/stage.py; nmake on the NT machine.")
    m.append("CC = cl")
    m.append("INC = /Int /Icore /Inacl\\include /Inacl\\include\\sodium /Izstd /Ibssl\\inc")
    m.append("CFLAGS = /nologo /c /O2 /W2 /FIcompat.h $(INC) /DCONFIGURED=1 /DSODIUM_STATIC /DWIN32_LEAN_AND_MEAN %s" % extra)
    m.append("BSSLFLAGS = /nologo /c /O2 /w /FIcompat.h /Int /Ibssl\\inc /Ibssl\\src "
             "/DBR_USE_URANDOM=0 /DBR_USE_GETENTROPY=0 /DBR_USE_UNIX_TIME=0 /DBR_RDRAND=0 "
             "/DBR_USE_WIN32_RAND=0 /DBR_USE_WIN32_TIME=0")
    m.append("ZFLAGS = /nologo /c /O2 /w /U_MSC_VER /FIcompat.h /Int /DHUF_FORCE_DECOMPRESS_X1 "
             "/DZSTD_FORCE_DECOMPRESS_SEQUENCES_SHORT /DZSTD_NO_INLINE")
    m.append("LIBS = wsock32.lib user32.lib gdi32.lib advapi32.lib shell32.lib ole32.lib uuid.lib")
    m.append("")
    objs, bobjs = [], []
    rules = []
    for n in nt:
        o = "obj\\nt_%s.obj" % n
        objs.append(o)
        flags = '$(CFLAGS) /DCDV_BUILD="\\"%s\\""' % build_id
        rules.append("%s: nt\\%s.c nt\\*.h\n\t$(CC) %s /Fo%s nt\\%s.c" % (o, n, flags, o, n))
    for n in CORE:
        o = "obj\\core_%s.obj" % n
        objs.append(o)
        rules.append("%s: core\\%s.c core\\*.h\n\t$(CC) $(CFLAGS) /Fo%s core\\%s.c" % (o, n, o, n))
    for f in nacl:
        o = "obj\\nacl_%s.obj" % os.path.basename(f)[:-2]
        objs.append(o)
        rules.append("%s: %s\n\t$(CC) $(CFLAGS) /w /Fo%s %s" % (o, win(f), o, win(f)))
    objs.append("obj\\zstddeclib.obj")
    rules.append("obj\\zstddeclib.obj: zstd\\zstddeclib.c\n\t$(CC) $(ZFLAGS) /Foobj\\zstddeclib.obj zstd\\zstddeclib.c")
    for f in bssl:
        o = "obj\\bssl_%s.obj" % os.path.basename(f)[:-2]
        bobjs.append(o)
        rules.append("%s: %s\n\t$(CC) $(BSSLFLAGS) /Fo%s %s" % (o, win(f), o, win(f)))
    has_rc = os.path.exists(os.path.join(OUT, "nt", "cdv.rc"))
    if has_rc:
        objs.append("obj\\cdv.res")
        rules.append("obj\\cdv.res: nt\\cdv.rc nt\\*.h nt\\*.ico\n\trc /r /Int /foobj\\cdv.res nt\\cdv.rc")

    m.append("OBJS = " + " \\\n\t".join(objs))
    m.append("BOBJS = " + " \\\n\t".join(bobjs))
    m.append("")
    m.append("all: obj C-Desk-Vint.exe")
    m.append("")
    m.append("objs: obj $(OBJS) bssl.lib")
    m.append("")
    m.append("obj:\n\tif not exist obj mkdir obj")
    m.append("")
    m.append("C-Desk-Vint.exe: $(OBJS) bssl.lib\n\tlink /nologo /subsystem:windows /out:$@ @<<\n$(OBJS) bssl.lib $(LIBS)\n<<")
    m.append("")
    m.append("bssl.lib: $(BOBJS)\n\tlib /nologo /out:$@ @<<\n$(BOBJS)\n<<")
    m.append("")
    m.extend(r + "\n" for r in rules)
    mk = "\r\n".join(m).replace("\n", "\r\n").replace("\r\r\n", "\r\n") + "\r\n"
    dst = os.path.join(OUT, "makefile")
    try:
        same = open(dst, "rb").read() == mk.encode()
    except OSError:
        same = False
    if not same:
        open(dst, "wb").write(mk.encode())
        written.append("makefile")
    print("staged %s: %d file(s) changed" % (OUT, len(written)))


if __name__ == "__main__":
    main()
